SPACE = 4          # px advance for the space
SIDE = 1           # side bearing on each side, so letters sit 2 px apart like the wordmark


def bitmap(ch):
    """Glyph as a boolean array on the full 14-row line (row 0 = cap line)."""
    top, rows = GLYPHS[ch]
    w = max(len(r) for r in rows)
    g = np.zeros((ASC + DESC, w), bool)
    for i, r in enumerate(rows):
        for j, c in enumerate(r):
            if c == "#":
                g[top + i, j] = True
    return g


def contours(g):
    """Trace the union outline of filled cells. Returns loops of (x, y) in pixel units, y up, baseline 0.
    Filled area stays on the right of each directed edge, so outer loops run clockwise (TrueType order)."""
    h, w = g.shape

    def filled(c, r):
        return 0 <= r < h and 0 <= c < w and g[r, c]

    edges = {}
    for r in range(h):
        for c in range(w):
            if not g[r, c]:
                continue
            y0 = ASC - 1 - r          # bottom edge of this row, in px above baseline
            y1 = y0 + 1
            if not filled(c, r - 1):
                edges.setdefault((c, y1), []).append((c + 1, y1))
            if not filled(c, r + 1):
                edges.setdefault((c + 1, y0), []).append((c, y0))
            if not filled(c - 1, r):
                edges.setdefault((c, y0), []).append((c, y1))
            if not filled(c + 1, r):
                edges.setdefault((c + 1, y1), []).append((c + 1, y0))

    def turn(prev, cur, nxt):
        ax, ay = cur[0] - prev[0], cur[1] - prev[1]
        bx, by = nxt[0] - cur[0], nxt[1] - cur[1]
        return ax * by - ay * bx       # < 0: right turn (y up)

    loops = []
    while edges:
        start = next(iter(edges))
        loop = [start]
        prev, cur = None, start
        while True:
            outs = edges[cur]
            if len(outs) > 1 and prev is not None:
                outs.sort(key=lambda n: turn(prev, cur, n))   # prefer the right turn at pinch points
            nxt = outs.pop(0)
            if not outs:
                del edges[cur]
            if nxt == start:
                break
            loop.append(nxt)
            prev, cur = cur, nxt
        # drop collinear points
        simp = []
        n = len(loop)
        for i in range(n):
            a, b, c2 = loop[i - 1], loop[i], loop[(i + 1) % n]
            if (b[0] - a[0]) * (c2[1] - b[1]) - (b[1] - a[1]) * (c2[0] - b[0]) != 0:
                simp.append(b)
        loops.append(simp)
    return loops


def build(out_dir, family="Munin Block", version="0.1"):
    from fontTools.fontBuilder import FontBuilder
    from fontTools.pens.t2CharStringPen import T2CharStringPen
    from fontTools.pens.ttGlyphPen import TTGlyphPen

    chars = list(GLYPHS)
    names = [".notdef", "space"] + [f"uni{ord(c):04X}" for c in chars]
    cmap = {32: "space", **{ord(c): f"uni{ord(c):04X}" for c in chars}}
    metrics, outlines = {}, {}
    nd = np.ones((ASC, 6), bool)
    nd[2:-2, 2:-2] = False
    outlines[".notdef"] = [[(x + SIDE, y) for x, y in l] for l in contours(np.vstack([nd, np.zeros((DESC, 6), bool)]))]
    metrics[".notdef"] = ((6 + 2 * SIDE) * PX, SIDE * PX)
    outlines["space"] = []
    metrics["space"] = (SPACE * PX, 0)
    for c, name in zip(chars, names[2:]):
        g = bitmap(c)
        outlines[name] = [[(x + SIDE, y) for x, y in l] for l in contours(g)]
        metrics[name] = ((g.shape[1] + 2 * SIDE) * PX, SIDE * PX)

    os.makedirs(out_dir, exist_ok=True)
    base = family.replace(" ", "")
    paths = {}
    for flavor in ("otf", "ttf"):
        fb = FontBuilder(16 * PX, isTTF=(flavor == "ttf"))
        fb.setupGlyphOrder(names)
        fb.setupCharacterMap(cmap)
        if flavor == "ttf":
            glyphs = {}
            for n in names:
                pen = TTGlyphPen(None)
                for loop in outlines[n]:
                    pen.moveTo((loop[0][0] * PX, loop[0][1] * PX))
                    for x, y in loop[1:]:
                        pen.lineTo((x * PX, y * PX))
                    pen.closePath()
                glyphs[n] = pen.glyph()
            fb.setupGlyf(glyphs)
        else:
            charstrings = {}
            for n in names:
                pen = T2CharStringPen(metrics[n][0], None)
                for loop in outlines[n]:
                    rev = loop[::-1]                      # CFF wants counter-clockwise outer contours
                    pen.moveTo((rev[0][0] * PX, rev[0][1] * PX))
                    for x, y in rev[1:]:
                        pen.lineTo((x * PX, y * PX))
                    pen.closePath()
                charstrings[n] = pen.getCharString()
            fb.setupCFF(base + "-Regular", {"FullName": family + " Regular"}, charstrings, {})
        fb.setupHorizontalMetrics(metrics)
        fb.setupHorizontalHeader(ascent=12 * PX, descent=-4 * PX)
        fb.setupNameTable({"familyName": family, "styleName": "Regular", "version": f"Version {version}",
                           "uniqueFontIdentifier": f"{base}-Regular;{version}", "psName": base + "-Regular"})
        fb.setupOS2(sTypoAscender=12 * PX, sTypoDescender=-4 * PX, sTypoLineGap=0, usWinAscent=12 * PX, usWinDescent=4 * PX,
                    sxHeight=X * PX, sCapHeight=ASC * PX, achVendID="MUNN", fsType=0)
        fb.setupPost(isFixedPitch=0, underlinePosition=-2 * PX, underlineThickness=PX)
        p =os.path.join(out_dir, f"{base}-Regular.{flavor}")
        fb.save(p)
        paths[flavor] = p
    from fontTools.ttLib import TTFont
    f = TTFont(paths["otf"])
    f.flavor = "woff2"
    paths["woff2"] = os.path.join(out_dir, f"{base}-Regular.woff2")
    f.save(paths["woff2"])
    return paths


